package io.github.kriolos.opos.automation.video;

import java.awt.image.BufferedImage;
import java.io.File;
import java.io.IOException;

/**
 * Pluggable SPI for screen recording and video encoding engines.
 *
 * <p>Enables interchangeable video recording implementations:
 * <ul>
 *   <li>Native system FFmpeg engine (encodes H.264 MP4 via rawvideo pipe)</li>
 *   <li>100% pure Java engine (encodes animated GIF and frame sequence HTML5 player)</li>
 * </ul>
 */
public interface VideoRecorderEngine {

    /**
     * Human-readable name of the video encoding engine.
     */
    String getName();

    /**
     * Checks if this engine is available in the current environment.
     */
    boolean isAvailable();

    /**
     * Initializes and starts the video recording output session.
     *
     * @param outputFile destination video/recording file
     * @param width      canvas width in pixels
     * @param height     canvas height in pixels
     * @param fps        target frames per second
     * @throws IOException if initialization or file creation fails
     */
    void start(File outputFile, int width, int height, int fps) throws IOException;

    /**
     * Records a single visual frame.
     *
     * @param frame buffered image containing the rendered Swing UI canvas
     */
    void recordFrame(BufferedImage frame);

    /**
     * Stops the recording session, finalizes the output container, and releases resources.
     */
    void stop();

    /**
     * Returns the output file generated by this engine.
     */
    File getOutputFile();
}
